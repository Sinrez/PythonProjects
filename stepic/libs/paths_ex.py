from pathlib import Path  # Импортируем модуль pathlib для работы с путями

# Определяем путь к папке внутри текущей директории
folder = Path.cwd() / "example_folder"  
folder.mkdir(parents=True, exist_ok=True)  # Создаем папку, если её нет

# Определяем путь к файлу внутри этой папки
p = folder / "example.txt"  
p.touch()  # Создаем пустой файл, если его нет

# Проверяем, существует ли путь (файл или папка)
print(f"Существует ли файл? {p.exists()}")  

# Проверяем, является ли это файлом
print(f"Это файл? {p.is_file()}")  

# Проверяем, является ли это директорией
print(f"Это папка? {p.is_dir()}")  

# Выводим путь к файлу (относительный)
print(f"Относительный путь: {p}")  

# Выводим абсолютный путь к файлу
print(f"Абсолютный путь: {p.resolve()}")  

# Выводим текущую директорию, в которой запущен скрипт
print(f"Текущая директория: {Path.cwd()}")  

# Выводим домашнюю директорию пользователя
print(f"Домашняя директория: {Path.home()}")  